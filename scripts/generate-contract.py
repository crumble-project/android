#!/usr/bin/env python3
"""Crumble Kotlin contract generator 1.0.0; Python standard library only."""
import argparse
import copy
import json
import pathlib
import re

VERSION = "1.0.0"
ROOT = pathlib.Path(__file__).resolve().parents[1]
PACKAGE = "dev.crumble.android.generated"
HEADER = "// Generated by scripts/generate-contract.py " + VERSION + ". Do not edit.\npackage " + PACKAGE + "\n\n"
IMPORTS = """import kotlinx.serialization.*
import kotlinx.serialization.builtins.*
import kotlinx.serialization.descriptors.*
import kotlinx.serialization.encoding.*
import kotlinx.serialization.json.*

"""
ALLOWED = {"$ref", "$schema", "$id", "$defs", "title", "description", "type", "properties", "required", "items", "additionalProperties", "enum", "const", "default", "format", "minLength", "maxLength", "pattern", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minItems", "maxItems", "allOf", "oneOf", "anyOf", "discriminator", "examples", "deprecated", "readOnly", "writeOnly"}


def pascal(value):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^a-zA-Z0-9]", value) if p)


def quoted(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def project(document, events):
    document = copy.deepcopy(document)
    schemas = document["components"]["schemas"]
    for name, event in events.items():
        event = copy.deepcopy(event)
        definitions = event.pop("$defs", {})
        mapping = {key: name + pascal(key) for key in definitions}
        def refs(value):
            if isinstance(value, dict):
                return {k: ("#/components/schemas/" + mapping[v.split("/")[-1]] if k == "$ref" and v.startswith("#/$defs/") else refs(v)) for k, v in value.items()}
            if isinstance(value, list):
                return [refs(v) for v in value]
            return value
        for key, value in definitions.items():
            schemas[mapping[key]] = refs(value)
        schemas[name] = refs(event)
    return document


class Generator:
    def __init__(self, document):
        self.document = document
        self.schemas = document["components"]["schemas"]
        self.models = {}
        self.request_models = set()
        self.rendered = {}

    def resolve(self, schema):
        self.validate(schema)
        if "$ref" in schema:
            if set(schema) - {"$ref", "description", "title", "examples", "deprecated"}:
                raise ValueError("unsupported reference siblings")
            ref = schema["$ref"]
            if not ref.startswith("#/components/schemas/"):
                raise ValueError("unsupported reference: " + ref)
            return self.resolve(self.schemas[ref.rsplit("/", 1)[1]])
        if "allOf" in schema:
            if set(schema) - {"allOf", "description", "title", "examples", "deprecated"}:
                raise ValueError("unsupported allOf siblings")
            result = {"type": "object", "properties": {}, "required": []}
            for part in schema["allOf"]:
                part = self.resolve(part)
                if part.get("type") != "object":
                    raise ValueError("allOf requires objects")
                for key, value in part.get("properties", {}).items():
                    if key in result["properties"] and result["properties"][key] != value:
                        raise ValueError("conflicting allOf property: " + key)
                    result["properties"][key] = value
                result["required"] += part.get("required", [])
            return result
        return schema

    def validate(self, schema):
        unknown = set(schema) - ALLOWED
        if unknown:
            raise ValueError("unsupported schema keywords: " + str(sorted(unknown)))
        if schema.get("additionalProperties") is False:
            raise ValueError("closed objects need an explicit codec; refusing to ignore additionalProperties:false")

    def type(self, schema, name, request=False):
        self.validate(schema)
        if "$ref" in schema:
            ref = schema["$ref"].rsplit("/", 1)[1]
            if not schema["$ref"].startswith("#/components/schemas/") or ref not in self.schemas:
                raise ValueError("unknown reference: " + schema["$ref"])
            if set(schema) - {"$ref", "description", "title", "examples", "deprecated"}:
                raise ValueError("unsupported reference siblings")
            target = "Request" + ref if request else ref
            self.register(target, self.schemas[ref], request)
            return target
        if "allOf" in schema:
            schema = self.resolve(schema)
        kind = schema.get("type")
        nullable = isinstance(kind, list) and "null" in kind
        if isinstance(kind, list):
            nonnull = [v for v in kind if v != "null"]
            if len(nonnull) != 1:
                raise ValueError("unsupported type union: " + str(kind))
            kind = nonnull[0]
        suffix = "?" if nullable else ""
        if "oneOf" in schema or "anyOf" in schema:
            branches = schema.get("oneOf", schema.get("anyOf"))
            nonnull = [part for part in branches if part != {"type": "null"}]
            if len(branches) == 2 and len(nonnull) == 1:
                return self.type(nonnull[0], name, request).rstrip("?") + "?"
            self.register(name, schema, request)
            return name
        if kind == "object":
            if "properties" not in schema:
                additional = schema.get("additionalProperties", {})
                return "Map<String, " + self.type(additional, name + "Value", request) + ">" + suffix
            self.register(name, schema, request)
            return name + suffix
        if kind == "array":
            return "List<" + self.type(schema["items"], name + "Item", request) + ">" + suffix
        primitives = {"string": "String", "number": "Double", "integer": "Long", "boolean": "Boolean", "null": "JsonNull"}
        if kind in primitives:
            return primitives[kind] + suffix
        if kind is None and not any(k in schema for k in ("properties", "items", "enum", "const")):
            return "JsonElement"
        raise ValueError("unsupported schema: " + str(schema))

    def register(self, name, schema, request=False):
        if name in self.models and self.models[name] != schema:
            raise ValueError("model name collision: " + name)
        self.models[name] = schema
        if request:
            self.request_models.add(name)

    def predicate(self, schema, value="element"):
        schema = self.resolve(schema)
        if "const" in schema:
            return value + " == Json.parseToJsonElement(" + quoted(json.dumps(schema["const"])) + ")"
        if "enum" in schema:
            return "(" + " || ".join(value + " == Json.parseToJsonElement(" + quoted(json.dumps(v)) + ")" for v in schema["enum"]) + ")"
        kind = schema.get("type")
        if isinstance(kind, list):
            return "(" + " || ".join(self.predicate(dict(schema, type=k), value) for k in kind) + ")"
        if kind == "object":
            checks = [value + " is JsonObject"]
            for key in schema.get("required", []):
                prop = schema.get("properties", {}).get(key, {})
                access = value + "[" + quoted(key) + "]"
                checks.append(access + " != null")
                if "enum" in prop or "const" in prop:
                    checks.append(self.predicate(prop, access))
            return "(" + " && ".join(checks) + ")"
        if kind == "string":
            return "(" + value + " is JsonPrimitive && " + value + ".isString)"
        if kind in ("number", "integer"):
            return "(" + value + " is JsonPrimitive && !" + value + ".isString && " + value + ".doubleOrNull != null)"
        if kind == "boolean":
            return "(" + value + " is JsonPrimitive && !" + value + ".isString && " + value + ".booleanOrNull != null)"
        if kind == "null":
            return value + " is JsonNull"
        raise ValueError("unsupported union branch: " + str(schema))

    def model(self, name, schema):
        self.validate(schema)
        schema = self.resolve(schema)
        union = schema.get("oneOf", schema.get("anyOf"))
        if union:
            types = [self.type(part, name + "Variant" + str(i + 1), name in self.request_models) for i, part in enumerate(union)]
            lines = ["@Serializable(with = " + name + "Codec::class)", "sealed class " + name + " {"]
            lines += ["    data class Variant" + str(i + 1) + "(val value: " + t + ") : " + name + "()" for i, t in enumerate(types)]
            lines += ["}", "object " + name + "Codec : KSerializer<" + name + "> {", "    override val descriptor: SerialDescriptor = buildClassSerialDescriptor(" + quoted(name) + ")", "    override fun deserialize(decoder: Decoder): " + name + " {", "        val input = decoder as JsonDecoder", "        val element = input.decodeJsonElement()"]
            if "oneOf" in schema:
                lines += ["        val matches = listOf(" + ", ".join(self.predicate(p) for p in union) + ")", "        require(matches.count { it } == 1) { " + quoted("Expected exactly one " + name + " variant") + " }"]
            lines += ["        return when {"]
            for i, part in enumerate(union):
                lines += ["            " + self.predicate(part) + " -> " + name + ".Variant" + str(i + 1) + "(input.json.decodeFromJsonElement<" + types[i] + ">(element))"]
            lines += ["            else -> throw SerializationException(" + quoted("Unknown " + name + " variant") + ")", "        }", "    }", "    override fun serialize(encoder: Encoder, value: " + name + ") {", "        val output = encoder as JsonEncoder", "        output.encodeJsonElement(when (value) {"]
            for i, t in enumerate(types):
                lines += ["            is " + name + ".Variant" + str(i + 1) + " -> output.json.encodeToJsonElement<" + t + ">(value.value)"]
            return "\n".join(lines + ["        })", "    }", "}"])
        if schema.get("type") != "object" or "properties" not in schema:
            raise ValueError("named schemas must be objects or unions: " + name)
        properties = schema.get("properties", {})
        if not properties:
            return "@Serializable\nclass " + name
        required = schema.get("required", [])
        request = name in self.request_models
        lines = ["@Serializable", "data class " + name + "("]
        for key, prop in properties.items():
            t = self.type(prop, name + pascal(key), request)
            if key not in required:
                if request:
                    lines += ["    @EncodeDefault(EncodeDefault.Mode.NEVER)"]
                    t, default = "OptionalField<" + t + ">", " = OptionalField.Absent"
                else:
                    t, default = t.rstrip("?") + "?", " = null"
            else:
                default = ""
            lines += ["    val `" + key + "`: " + t + default + ","]
        return "\n".join(lines + [")"])

    def operations(self):
        lines = ["class ContractOperations(private val boundary: ContractBoundary) {"]
        for path, methods in self.document["paths"].items():
            for method, operation in methods.items():
                if method not in ("get", "post", "patch", "put", "delete"):
                    raise ValueError("unsupported path entry: " + method)
                op = operation["operationId"]
                params, query = [], []
                route = quoted(path)
                for param in operation.get("parameters", []):
                    key = param["name"]
                    t = self.type(param["schema"], pascal(op) + pascal(key))
                    optional = not param.get("required", False)
                    params.append("`" + key + "`: " + t + ("? = null" if optional else ""))
                    if param["in"] == "path":
                        value = "`" + key + "`" + ("" if t == "String" else ".toString()")
                        route = route.replace("{" + key + "}", "${boundary.escape(" + value + ")}")
                    elif param["in"] == "query":
                        value = "it" if t == "String" else "it.toString()"
                        query.append("        `" + key + "`" + ("?.let" if optional else ".let") + " { query.add(" + quoted(key + "=") + " + boundary.escape(" + value + ")) }")
                    else:
                        raise ValueError("unsupported parameter location")
                body = "null"
                if "requestBody" in operation:
                    content = operation["requestBody"]["content"]
                    if list(content) != ["application/json"]:
                        raise ValueError("unsupported request media type")
                    t = self.type(content["application/json"]["schema"], pascal(op) + "Request", True)
                    params.insert(0, "body: " + t)
                    body = "boundary.json.encodeToString(body).toByteArray(Charsets.UTF_8)"
                params.append("timeoutMs: Int = 20_000")
                success = [(status, value) for status, value in operation["responses"].items() if status.startswith("2")]
                if len(success) != 1:
                    raise ValueError("multiple success responses require explicit support")
                content = success[0][1].get("content", {})
                media = next(iter(content), None)
                if len(content) > 1:
                    raise ValueError("multiple success media types")
                streaming = media == "text/event-stream"
                if media == "application/json":
                    t = self.type(content[media]["schema"], pascal(op) + "Response")
                elif media == "image/*":
                    t = "ByteArray"
                elif media is None:
                    t = "Unit"
                elif streaming:
                    t = "HttpRequestData"
                else:
                    raise ValueError("unsupported success media: " + media)
                lines += ["    suspend fun " + op + "(" + ", ".join(params) + "): " + t + " {"]
                lines += ["        val query = mutableListOf<String>()"] + query
                lines += ["        val path = " + route + ' + if (query.isEmpty()) "" else "?" + query.joinToString("&")']
                if streaming:
                    lines += ["        return boundary.request(" + quoted(method.upper()) + ", path, " + body + ", timeoutMs)"]
                else:
                    call = "boundary.send(" + quoted(method.upper()) + ", path, " + body + ", timeoutMs)"
                    if t == "Unit":
                        lines += ["        " + call]
                    elif t == "ByteArray":
                        lines += ["        return " + call]
                    else:
                        lines += ["        val bytes = " + call, "        return boundary.json.decodeFromString<" + t + ">(bytes.toString(Charsets.UTF_8))"]
                lines += ["    }", ""]
        return "\n".join(lines + ["}"])

    def generate(self, output):
        for name, schema in list(self.schemas.items()):
            self.register(name, schema)
        operations = self.operations()
        while set(self.models) - set(self.rendered):
            for name in sorted(set(self.models) - set(self.rendered)):
                self.rendered[name] = self.model(name, self.models[name])
        output.mkdir(parents=True, exist_ok=True)
        models = "@file:OptIn(kotlinx.serialization.ExperimentalSerializationApi::class)\n" + HEADER + IMPORTS + "\n\n".join(self.rendered[name] for name in sorted(self.rendered)) + "\n"
        (output / "ContractModels.kt").write_text(models)
        (output / "ContractOperations.kt").write_text(HEADER + IMPORTS + "import dev.crumble.android.network.HttpRequestData\n\n" + operations + "\n")
        template = ROOT / "scripts/templates/ContractBoundary.kt"
        (output / "ContractBoundary.kt").write_text(HEADER + template.read_text())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--assets", type=pathlib.Path, default=ROOT / "contract/assets")
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / "app/src/main/java/dev/crumble/android/generated")
    args = parser.parse_args()
    document = json.loads((args.assets / "openapi.json").read_text())
    events = {name: json.loads((args.assets / filename).read_text()) for name, filename in [("SnapshotEventPayload", "chat-snapshot.schema.json"), ("ActivityEventPayload", "activity-event.schema.json"), ("HeartbeatEventPayload", "heartbeat.schema.json")]}
    event_projection = project({"openapi": "3.1.0", "info": {"title": "Crumble SSE payloads", "version": document["info"]["version"]}, "components": {"schemas": {}}, "paths": {}}, events)
    for name, schema in event_projection["components"]["schemas"].items():
        if name in document["components"]["schemas"]:
            raise ValueError("event projection collides with HTTP schema: " + name)
        document["components"]["schemas"][name] = schema
    Generator(document).generate(args.output)
    (args.output / "event-projection.json").write_text(json.dumps(event_projection, indent=2, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
